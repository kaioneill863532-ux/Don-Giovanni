"""Pack prototype/assets/* into prototype/assets.js (window.DG_ASSETS = {...}).

The greybox loads assets.js with a plain <script> tag, so index.html still works
when opened straight from disk (file://), where fetch() of local files is blocked.

    python prototype/tools/build_assets.py
"""
import base64, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
MIME = {".glb": "model/gltf-binary", ".png": "image/png", ".jpg": "image/jpeg"}
FILES = [
    "mask_don.glb", "mask_anna.glb", "mask_servant.glb",
    "icon_don.png", "icon_anna.png", "icon_servant.png",
    "vignette_don.png", "vignette_anna.png", "vignette_servant.png",
]

def main():
    out = {}
    for name in FILES:
        path = ASSETS / name
        data = base64.b64encode(path.read_bytes()).decode("ascii")
        out[path.stem] = f"data:{MIME[path.suffix]};base64,{data}"
    js = "// Generated by tools/build_assets.py. Do not edit by hand.\nwindow.DG_ASSETS = " + json.dumps(out, indent=0) + ";\n"
    (ROOT / "assets.js").write_text(js, encoding="utf-8")
    print("wrote", ROOT / "assets.js", f"{len(js) / 1024:.0f} KB")

if __name__ == "__main__":
    main()
